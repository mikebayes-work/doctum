// scripts/build.js — Netlify build step (`node scripts/build.js`). No dependencies.
//
// Same shape as The Grid's scripts/build-db.js:
//   1. Read data/listings.json (written by the scraper; SERVER-ONLY).
//   2. Write netlify/doctum/listings.generated.js — the database as a JS module
//      that Netlify bundles INTO the edge functions. It is gitignored and is
//      never copied to dist/, so it never has a public URL.
//   3. Copy an explicit allowlist of public files into dist/.
//   4. Build the static, crawlable pages (scripts/pages.js).
//   5. Write dist/_headers (CSP and security headers).
//
// Environment (Netlify → Site configuration → Environment variables):
//   SITE_URL        default https://doctum.co.uk
//   ALLOW_INDEXING  "true" to let search engines index the site. Anything else
//                   = noindex everywhere + robots.txt Disallow (safe default
//                   while the site is being set up on a netlify.app URL).
//   GA_ID           optional Google Analytics 4 id (G-XXXX). Off if unset.

const fs = require('fs');
const path = require('path');
const { buildPages, slugify } = require('./pages.js');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const SITE = (process.env.SITE_URL || 'https://doctum.co.uk').replace(/\/+$/, '');
const INDEX = String(process.env.ALLOW_INDEXING).toLowerCase() === 'true';
const GA_ID = /^G-[A-Z0-9]{4,14}$/.test(process.env.GA_ID || '') ? process.env.GA_ID : '';

function fail(msg) { console.error('BUILD FAILED: ' + msg); process.exit(1); }

// ── 1. Data ────────────────────────────────────────────────────────────
const src = path.join(ROOT, 'data', 'listings.json');
if (!fs.existsSync(src)) fail('data/listings.json is missing (run the scraper export).');
const db = JSON.parse(fs.readFileSync(src, 'utf8'));
const rows = Array.isArray(db.listings) ? db.listings : [];
const open = rows.filter((r) => r.status === 'open');
if (!open.length) fail('0 open listings in data/listings.json — refusing to deploy an empty site.');

const used = new Set();
for (const r of rows) {
  if (!/^[0-9a-f]{12}$/.test(r.id || '')) fail(`bad listing id ${JSON.stringify(r.id)}`);
  const slug = slugify(r.title || 'phd').slice(0, 70).replace(/-+$/, '') || 'phd';
  r.path = `/phd/${slug}-${r.id}/`;
  if (used.has(r.path)) fail(`duplicate path ${r.path}`);
  used.add(r.path);
}
const builtAt = db.meta?.generated || new Date().toISOString();

// ── 2. Server-only module ─────────────────────────────────────────────
const gen = path.join(ROOT, 'netlify', 'doctum', 'listings.generated.js');
const payload = JSON.stringify({ builtAt, rows });
fs.writeFileSync(gen,
  '// GENERATED by scripts/build.js — do not edit, do not commit, never publish.\n' +
  `export default JSON.parse(${JSON.stringify(payload)});\n`);
console.log(`db module: ${rows.length} listings (${open.length} open), ${(payload.length / 1024).toFixed(0)} KB`);

// ── 3. Public files (explicit allowlist) ──────────────────────────────
fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });
const copy = (from, to) => {
  const a = path.join(ROOT, from), b = path.join(DIST, to);
  if (!fs.existsSync(a)) fail(`allowlisted file missing: ${from}`);
  fs.mkdirSync(path.dirname(b), { recursive: true });
  fs.copyFileSync(a, b);
};
const PUBLIC = [
  ['public/assets/site.css', 'assets/site.css'],
  ['public/assets/site.js', 'assets/site.js'],
  ['public/assets/search.js', 'assets/search.js'],
  ['public/assets/match.js', 'assets/match.js'],
  ['public/assets/briefing.js', 'assets/briefing.js'],
  ['brand/logo.svg', 'brand/logo.svg'],
  ['brand/logo-dark.svg', 'brand/logo-dark.svg'],
  ['brand/logo-nav.svg', 'brand/logo-nav.svg'],
  ['brand/logo-nav-dark.svg', 'brand/logo-nav-dark.svg'],
  ['brand/mark.svg', 'brand/mark.svg'],
  ['brand/mark-dark.svg', 'brand/mark-dark.svg'],
  ['brand/og-image.png', 'brand/og-image.png'],
  ['brand/icon-512.png', 'brand/icon-512.png'],
  ['brand/favicon.svg', 'favicon.svg'],
  ['brand/icon-32.png', 'favicon-32.png'],
  ['brand/icon-180.png', 'apple-touch-icon.png'],
];
for (const [a, b] of PUBLIC) copy(a, b);

// ── 4. Pages ──────────────────────────────────────────────────────────
const count = buildPages({ rows, builtAt, site: SITE, index: INDEX, gaId: GA_ID, dist: DIST, root: ROOT });
console.log(`pages: ${count} written (indexing ${INDEX ? 'ON' : 'OFF'}, GA ${GA_ID ? 'on' : 'off'}, site ${SITE})`);

// ── 5. Headers ────────────────────────────────────────────────────────
const ga = GA_ID ? ' https://www.googletagmanager.com' : '';
const gaConnect = GA_ID ? ' https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com' : '';
const csp = [
  "default-src 'self'",
  `script-src 'self' https://cdnjs.cloudflare.com${ga}`,
  "style-src 'self' https://fonts.googleapis.com",
  "font-src https://fonts.gstatic.com",
  `img-src 'self' data:${GA_ID ? ' https://*.google-analytics.com https://www.googletagmanager.com' : ''}`,
  `connect-src 'self'${gaConnect}`,
  "worker-src 'self' blob: https://cdnjs.cloudflare.com",
  "frame-ancestors 'none'", "base-uri 'self'", "form-action 'self'", "object-src 'none'",
].join('; ');
fs.writeFileSync(path.join(DIST, '_headers'), `/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
${INDEX ? '' : '  X-Robots-Tag: noindex\n'}
/assets/*
  Cache-Control: public, max-age=31536000, immutable
/brand/*
  Cache-Control: public, max-age=604800
`);

// ── Safety check: nothing private in dist/ ────────────────────────────
const bad = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.(json|db|yaml|py|sqlite)$/i.test(f) || /generated/.test(f)) bad.push(path.relative(DIST, p));
  }
})(DIST);
if (bad.length) fail('private-looking files ended up in dist/: ' + bad.join(', '));
console.log('build OK');
